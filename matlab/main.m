%% =======================================================================
%  输入参数区  —— 日常只改这一块
%  ----------------------------------------------------------------------
%  层参数矩阵，每行一层 [层厚 cm, 回弹模量 MPa, 泊松比]
%    最后一行为半无限土基，厚度必须填 Inf
%    模量 MPa、泊松比 0~0.5（不含 0.5）、非底层厚度 > 0
% =======================================================================

LAYERS = [   4    9800    0.25 ;    % 1 上面层
             6   12500    0.25 ;    % 2 中面层
             8   11500    0.25 ;    % 3 下面层
            12    9000    0.25 ;    % 4 上基层
            18   14000    0.25 ;    % 5 中基层
            18   12000    0.25 ;    % 6 下基层
            15     300    0.35 ;    % 7 底基层
           Inf      60    0.40 ];   % 8 土基（半无限）

P_kN = 50;        % 圆形均布荷载合力 (kN)，FWD 标准 50 kN
R_cm = 15;        % 荷载圆半径 (cm)，φ300 mm 承载板即 15 cm

%% =======================================================================
%  以下无需修改
% =======================================================================

t0  = tic;
out = pavement_deflection(LAYERS, P_kN, R_cm);
dt  = toc(t0);

nF   = size(LAYERS, 1) - 1;
Htot = sum(LAYERS(1:nF, 1));

fprintf('\n');
fprintf('  层数         : %d（有限层 %d 层，总厚 %.1f cm）\n', nF + 1, nF, Htot);
fprintf('  荷载         : P = %.2f kN, a = %.1f mm (φ%.0f mm)\n', P_kN, out.a, 2 * out.a);
fprintf('  接地压力     : p = %.6f MPa\n', out.p);
fprintf('  积分上限     : xi_max = %.4f 1/mm (S = %.1f)\n', out.xi_max, out.S);
fprintf('  ------------------------------------------------------------\n');
fprintf('  圆心弯沉 w   : %.5f  (0.01 mm)\n', out.w_001mm);
fprintf('                  %.7f  (mm)\n', out.w_mm);
fprintf('  ------------------------------------------------------------\n');
fprintf('  核调用 %d 次，用时 %.2f s\n\n', out.nEval, dt);
